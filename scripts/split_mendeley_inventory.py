#!/usr/bin/env python3
"""Create source/participant-grouped train/val/test video manifests for verified Mendeley inventory."""
import argparse
import csv
import random
from collections import Counter,defaultdict
from pathlib import Path

CATEGORIES=[("squat","correct"),("squat","incorrect"),("pushup","correct"),("pushup","incorrect")]

def write_csv(path, rows, columns):
    with path.open("w",encoding="utf-8",newline="") as f:
        w=csv.DictWriter(f,fieldnames=columns);w.writeheader();w.writerows(rows)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--inventory",type=Path,default=Path("data/prepared/mendeley_inventory.csv"))
    p.add_argument("--output",type=Path,default=Path("data/prepared/mendeley"))
    p.add_argument("--data-card",type=Path,default=Path("docs/data_cards/DATA_CARD_MENDELEY.md"))
    a=p.parse_args()
    with a.inventory.open(newline="",encoding="utf-8") as f:
        reader=csv.DictReader(f)
        wanted={"relative_video_path","exercise","form_label","participant_id","requires_review"}
        if not reader.fieldnames or not wanted.issubset(reader.fieldnames):p.error("Missing expected inventory columns")
        rows=list(reader)
    if not rows:p.error("Empty inventory")
    for r in rows:
        if r["requires_review"]=="YES" or "REVIEW" in (r["form_label"],r["participant_id"]):
            p.error("Unverified labels/participant IDs remain. Correct the CSV manually and set requires_review=NO after verification.")
        if (r["exercise"],r["form_label"]) not in CATEGORIES:
            p.error(f"Unknown exercise/form: {r['exercise']} {r['form_label']}")
        if not r["relative_video_path"]:p.error("Missing video path")
    if len({r["relative_video_path"] for r in rows}) != len(rows):p.error("Duplicate video paths")
    groups=defaultdict(list)
    for r in rows:groups[r["participant_id"]].append(r)
    subjects=sorted(groups)
    if len(subjects)<6:p.error("Need at least six distinct verified participant IDs for three-way split")
    if len({(r["exercise"],r["form_label"]) for r in rows})!=4:
        p.error("Data missing at least one of squat/pushup x correct/incorrect labels. Recheck inventory and dataset files.")
    n=len(subjects);train_n=round(n*.70);val_n=round(n*.15)
    train_n=max(1,min(n-2,train_n));val_n=max(1,min(n-train_n-1,val_n))
    proportions={"train":.70,"val":.15,"test":.15}
    rng=random.Random(20261023)
    best=None
    total=Counter((r["exercise"],r["form_label"]) for r in rows)
    for _ in range(7000):
        perm=rng.sample(subjects,len(subjects))
        people={"train":set(perm[:train_n]),"val":set(perm[train_n:train_n+val_n]),"test":set(perm[train_n+val_n:])}
        stats={key:Counter((r["exercise"],r["form_label"]) for subj in ppl for r in groups[subj]) for key,ppl in people.items()}
        score=0
        for split,pct in proportions.items():
            count=sum(stats[split].values())
            score += abs(count/len(rows)-pct)*8
            for label in CATEGORIES:
                actual=stats[split][label]
                score += abs(actual-pct*total[label])/max(1,total[label])*.35
                if actual==0:score+=10
        if best is None or score<best[0]:best=(score,people)
    mapping={person:split for split,ss in best[1].items() for person in ss}
    for r in rows:r["split"]=mapping[r["participant_id"]]
    a.output.mkdir(parents=True,exist_ok=True)
    fields=list(rows[0])
    for split in ("train","val","test"):
        write_csv(a.output/f"{split}_videos.csv",[r for r in rows if r["split"]==split],fields)
    write_csv(a.output/"all_videos.csv",rows,fields)
    write_csv(a.output/"subject_assignments.csv",[{"participant_id":s,"split":mapping[s]} for s in subjects],["participant_id","split"])
    stats=Counter((r["exercise"],r["form_label"],r["split"]) for r in rows)
    content=["# POSTURE CHECK — Milestone 2 Data Card (Mendeley subset)","",
        "**Dataset:** A Multi-View Raw Video Dataset of Seven Fitness Exercises with Good/Bad Form Labels, v3 (2026)",
        "**Link:** https://data.mendeley.com/datasets/kgbb3yn47p/3",
        "**License:** CC BY 4.0 (attribution required).",
        "**Selection:** Bodyweight squat and conventional push-up MP4 recordings; 26 original subjects in complete dataset (subset count below).",
        "**Source labels:** video-level manual good/bad form, exercise identity, subject ID, and camera viewpoint; review inventory verified before splitting.",
        "**Split:** participant-disjoint approximate 70/15/15; dataset source tracked separately from REHAB24.",
        "**Resolution/preprocessing:** not yet measured; inspect video dimensions and fps before extraction. No images or poses were generated by these scripts.",
        "**Known gaps:** no lunges/jumping jacks here; gym-only viewpoints; no frame-level localization of faults; variable exercise clips.","",
        "| Exercise | Form | Train videos | Val videos | Test videos | Total videos |",
        "|---|---|---:|---:|---:|---:|"]
    for ex,label in CATEGORIES:
        nums=[stats[ex,label,split] for split in ("train","val","test")]
        content.append(f"| {ex} | {label} | {nums[0]} | {nums[1]} | {nums[2]} | {sum(nums)} |")
    content += ["",f"**Selected videos:** {len(rows)}; **verified subjects:** {len(subjects)}.",
                "**Important:** If quality labels apply to whole video, do not assume every individual frame visibly shows an error."]
    a.data_card.parent.mkdir(parents=True,exist_ok=True)
    a.data_card.write_text("\n".join(content)+"\n",encoding="utf-8")
    print(f"[ok] {len(rows)} videos, {len(subjects)} participants; grouped split manifests in {a.output}")
    for split in ("train","val","test"):
        print(f" {split}: {sum(r['split']==split for r in rows)} videos; {len(best[1][split])} participants")

if __name__=="__main__":main()
